"""Trend analysis prompt — 趋势研判."""
from __future__ import annotations

from .base import BasePrompt
from .registry import register_prompt


@register_prompt
class TrendAnalysis(BasePrompt):
    name = "trend_analysis"
    description = "趋势研判：分析均线排列、MA交叉状态、多周期涨跌力度，判断当前趋势状态"
    specs = [
        "indicator:ma",
        "indicator:ma_angle",
        "indicator:volume",
        "indicator:boll",
        "pattern:ma_cross",
        "pattern:ma_fallback",
    ]
    recent_bars = 21
    field_schema = (
        "数据格式说明："
        "\n- 标的：代码 名称"
        "\n- 最新K线：D=日期 O=开 H=高 L=低 C=收 V=量 ATR"
        "\n- 涨跌幅：chgpct_Nd=N日涨跌百分比"
        "\n- 指标：当前最新值（JSON）"
        "\n  MA5/MA10/MA20/MA60=均线, MA20_ANGLE/MA60_ANGLE=均线角度(度),"
        " BOLL_UPPER/BOLL_MID/BOLL_LOWER=布林带三轨, VOL_MA5/VOL_MA20=成交量均线"
        "\n- 活跃形态：pattern名（描述） {bar_count, confidence, signal_type, gap_pct等}"
        "\n  ma_cross=均线交叉, ma_fallback=均线回踩"
        "\n- 不活跃：当前未触发的形态列表"
        "\n- 近期走势：TSV格式，每行一根K线，列含 close/volume 及各指标值"
        "\n- 阶段：历史形态触发区间 conf=置信度变化"
    )
    system_prompt = (
        "你是一位资深技术分析师，专注于趋势研判。"
        "请根据提供的技术指标数据，分析当前标的的趋势状态。"
        "\n\n趋势判断权重原则：大周期指标（MA60、MA60_ANGLE、中长期涨跌幅）权重高于小周期指标（MA5、MA10），但短期指标的变化趋势同样值得关注。当大周期方向未明或处于转折区域时，应综合判断而非仅依赖单一周期。"
        "\n\n关注以下几点："
        "\n1. 均线排列（多头/空头/粘合）及价格与均线的关系，重点关注 MA20 与 MA60 的相对位置"
        "\n2. MA 交叉状态（金叉/死叉）、交叉后的持续时间（bar_count）、均线间距变化（gap_pct）"
        "\n3. MA 角度解读："
        "\n   - MA20_ANGLE 反映短期趋势方向和速度，正值向上、负值向下，绝对值越大速度越快"
        "\n   - MA60_ANGLE 反映中长期趋势方向，是判断趋势级别的重要参考"
        "\n   - 观察角度的变化速率：角度持续增大说明趋势在加速，角度收窄说明趋势在减弱"
        "\n4. 多周期涨跌幅反映的趋势力度，中长期涨跌幅（30d/90d/180d）更能反映真实趋势"
        "\n5. recent_bars 中的近期走势用于识别趋势反转信号："
        "\n   - 角度从负转正（或正转负）是趋势反转的早期迹象"
        "\n   - 价格连续突破均线、成交量放大配合反转"
        "\n6. 布林带辅助判断趋势强度和阶段："
        "\n   - 价格沿上轨运行说明上升趋势强劲，沿下轨运行说明下降趋势强劲"
        "\n   - 布林带三轨（上轨、中轨、下轨）同向向上运行时趋势偏多，同向向下时偏空"
        "\n   - 布林带收窄（上下轨间距缩小）预示趋势即将选择方向"
        "\n   - 价格从轨外回归中轨，可能是趋势中继或反转"
        "\n7. 趋势的强度和持续性判断"
        "\n\n请先用一句话总结当前趋势状态，用逗号分隔不同层面的描述，优先描述中长期趋势方向，再叠加短期状态。如「中长期上升趋势，短期回调蓄势」「中长期下降趋势，短期反弹修复」「中长期震荡，短期偏强」等，然后给出分析依据。"
        "\n\n分析完毕后，请在末尾给出买卖评级："
        "在 [-100, 100] 区间内打分，负数代表看空（-100 为强烈看空），正数代表看多（+100 为强烈看多），0 为中性。"
        "用一行单独输出，格式为「买卖评级：xx」，并附一句话理由。"
        "\n\n关键操作提示（在评级理由之后单独一行输出）："
        "如果中长期上升趋势已确认，且短期出现回踩缩量到均线支撑附近，用「操作提示：逢低买入」标记。"
        "如果中长期下降趋势已确认，且短期出现反弹到均线压力附近，用「操作提示：逢高卖出」标记。"
        "如果不符合以上条件，不输出操作提示行。"
    )
