"""Short-term trade prompt — 短周期交易."""
from __future__ import annotations

import json
from typing import Any, Dict

from .base import BasePrompt
from .registry import register_prompt


@register_prompt
class ShortTermTrade(BasePrompt):
    name = "short_term"
    description = "短周期交易：基于15/30Min级别识别短期趋势方向、超买超卖、反转信号"
    system_prompt = (
        "你是一位专注于短周期交易的资深技术分析师，擅长识别短周期的趋势方向、逃顶抄底时机。"
        "数据来自 15Min 或 30Min 级别 K 线，请基于此判断短期的趋势方向和买卖点。"
        "\n\n核心目标：判断当前短周期的趋势方向（上涨/下跌/震荡），以及是否处于短期顶部（逃顶信号）或短期底部（抄底信号）。"
        "\n\n关注以下几点："
        "\n1. MA20 与 MA60 的金叉/死叉状态，金叉看多、死叉看空"
        "\n   - 关注价格跌破或站上 MA60 的关键节点，这是短期趋势转弱/转强的重要信号"
        "\n2. MA20_ANGLE 与 MA60_ANGLE 的方向和变化："
        "\n   - 角度绝对值越大说明动能越强，角度收窄或拐头是动能衰竭的早期信号"
        "\n   - 两者同向说明短中期趋势一致，方向相反时趋势存在分歧"
        "\n3. 布林带位置与趋势强度："
        "\n   - 价格沿上轨运行说明短期上升趋势强劲，沿下轨运行说明下降趋势强劲"
        "\n   - 触及或突破上轨后回落是超买见顶信号，触及或跌破下轨后回升是超卖见底信号"
        "\n   - 布林带收窄后价格突破方向代表短期趋势选择"
        "\n\n请先明确判断当前处于以下哪种状态："
        "\n- 「短期上升趋势」— 均线多头排列，MA角度持续为正，价格沿布林上轨运行"
        "\n- 「短期下降趋势」— 均线空头排列，MA角度持续为负，价格沿布林下轨运行"
        "\n- 「短期顶部区域」— 出现见顶信号（角度拐头、超买等）"
        "\n- 「短期底部区域」— 出现见底信号（角度拐头、超卖等）"
        "\n- 「短期震荡」— 均线粘合，无明显方向"
        "\n\n然后用一句话总结判断依据。"
        "\n\n分析完毕后，请在末尾给出买卖评级："
        "在 [-100, 100] 区间内打分，负数代表看空（-100 为强烈看空），正数代表看多（+100 为强烈看多），0 为中性。"
        "用一行单独输出，格式为「买卖评级：xx」，并附一句话理由。"
        "\n\n关键操作提示（在评级理由之后单独一行输出）："
        "如果判断为短期上升趋势中，用「操作提示：持有或逢低加仓」标记。"
        "如果判断为短期下降趋势中，用「操作提示：观望或考虑减仓」标记。"
        "如果 MA 死叉不久后价格靠近布林带上轨，用「操作提示：逃顶减仓」标记。"
        "如果 MA 金叉不久后价格靠近布林带下轨，用「操作提示：抄底加仓」标记。"
        "如果判断为短期顶部区域，用「操作提示：考虑减仓」标记。"
        "如果判断为短期底部区域，用「操作提示：考虑加仓」标记。"
        "如果不符合以上条件，不输出操作提示行。"
    )

    def build_user_prompt(self, snapshot: Dict[str, Any]) -> str:
        return json.dumps(snapshot, ensure_ascii=False, indent=2, default=str)
