"""Short-term trade prompt — 短周期交易."""
from __future__ import annotations

from .base import BasePrompt
from .registry import register_prompt


@register_prompt
class ShortTermTrade(BasePrompt):
    name = "short_term"
    description = "短周期交易：基于15/30Min级别识别短期趋势方向、回调买点、反弹卖点、趋势转折"
    specs = [
        "indicator:ma",
        "indicator:ma_angle",
        "indicator:boll",
        "indicator:bias",
        "indicator:rsi",
        "indicator:atr",
        "pattern:ma_cross",
        "pattern:ma_fallback",
    ]
    recent_bars = 55
    field_schema = (
        "数据格式说明："
        "\n- 标的：代码 名称"
        "\n- 最新K线：D=日期 O=开 H=高 L=低 C=收 V=量 ATR"
        "\n- 涨跌幅：chgpct_Nd=N日涨跌百分比"
        "\n- 指标：当前最新值（JSON）"
        "\n  MA5/MA10/MA20/MA60=均线, MA20_ANGLE/MA60_ANGLE=均线角度(度),"
        " BOLL_UPPER/BOLL_MID/BOLL_LOWER=布林带三轨, BIAS6=乖离率, RSI14=相对强弱"
        "\n- 活跃形态：pattern名（描述） {bar_count, confidence, signal_type等}"
        "\n- 不活跃：当前未触发的形态列表"
        "\n- 近期走势：TSV格式，每行一根K线，列含 close/volume 及各指标值"
        "\n- 阶段：历史形态触发区间 conf=置信度变化"
    )
    system_prompt = (
        "你是一位专注于短周期交易的资深技术分析师。"
        "数据来自 15Min 或 30Min 级别 K 线。"
        "\n\n分析框架 — 先定大方向，再判当前位置："
        "\n第一步：判断大方向。看 MA60_ANGLE 的方向和 MA20 与 MA60 的排列关系。"
        "MA60_ANGLE 持续为正且 MA20 > MA60 → 大方向为多；"
        "MA60_ANGLE 持续为负且 MA20 < MA60 → 大方向为空。"
        "\n第二步：在大方向框架内判断当前位置。MA20_ANGLE 反映短期动能，"
        "可能出现与大方向相反的短期波动（回调或反弹），这是关键交易机会。"
        "\n\n请判断当前处于以下哪种状态："
        "\n\n── 上升趋势中的状态（MA60_ANGLE 为正，MA20 > MA60，金叉状态）──"
        "\n「上升趋势·回调买点」— 核心条件：MA60_ANGLE 在 recent_bars 中保持稳定或持续向上"
        "（中期趋势向上且未走弱），同时 MA20_ANGLE 因短期调整转为负值或接近零，"
        "价格从高位回落至 MA20 附近或下方。这是上升趋势中的良性回调，MA60 提供趋势支撑，是加仓良机。"
        "\n「上升趋势·加速上行」— MA20_ANGLE 和 MA60_ANGLE 均为正且稳定，"
        "价格在 MA20 之上运行，趋势健康。"
        "\n「上升趋势·见顶预警」— 核心条件：MA60_ANGLE 在 recent_bars 中已出现明显下滑"
        "（从高位持续走弱），MA20_ANGLE 从高位快速回落转负，"
        "价格出现滞涨或冲高回落。趋势可能即将结束，需警惕反转。"
        "\n区分「回调买点」与「见顶预警」的关键：看 MA60_ANGLE 在 recent_bars 中的走势。"
        "如果 MA60_ANGLE 依然坚挺或上升 → 回调买点；如果 MA60_ANGLE 已从高位明显下滑 → 见顶预警。"
        "\n\n── 下降趋势中的状态（MA60_ANGLE 为负，MA20 < MA60，死叉状态）──"
        "\n「下降趋势·反弹卖点」— 核心条件：MA60_ANGLE 在 recent_bars 中保持稳定或持续向下"
        "（中期趋势向下且未走弱），同时 MA20_ANGLE 因短期反弹转为正值或接近零，"
        "价格从低位反弹至 MA20 附近或上方。这是下降趋势中的技术性反弹，MA60 构成压力，是减仓逃命的机会。"
        "\n「下降趋势·见底预警」— 核心条件：MA60_ANGLE 在 recent_bars 中已出现明显回升"
        "（从低位持续走强），MA20_ANGLE 从低位快速回升即将转正，"
        "价格出现止跌企稳，RSI 偏低。趋势可能即将结束，需关注但尚未确认反转。"
        "\n区分「反弹卖点」与「见底预警」的关键：看 MA60_ANGLE 在 recent_bars 中的走势。"
        "如果 MA60_ANGLE 依然稳定向下或持续走低 → 反弹卖点；如果 MA60_ANGLE 已从低位明显回升 → 见底预警。"
        "\n「下降趋势·加速下行」— MA20_ANGLE 和 MA60_ANGLE 均为负且稳定，"
        "价格在 MA20 之下运行，趋势健康（对空头而言）。"
        "\n\n── 趋势转折（大方向切换的关键节点）──"
        "\n「多转空节点」— 此前处于明确的上升趋势（MA20 > MA60，MA60_ANGLE 持续为正），"
        "现在 MA60_ANGLE 明确从正转负，MA20_ANGLE 同步向下，"
        "价格跌破 MA60，死叉即将或刚刚发生。"
        "判断要点：MA60_ANGLE 的方向变化是核心，它代表中期趋势的实质性转向，"
        "而非仅仅是 MA20_ANGLE 的短期波动。"
        "\n「空转多节点」— 此前处于明确的下降趋势（MA20 < MA60，MA60_ANGLE 持续为负），"
        "现在 MA60_ANGLE 明确从负转正，MA20_ANGLE 同步向上，"
        "价格站上 MA60，金叉即将或刚刚发生。"
        "判断要点：MA60_ANGLE 必须有实质性走强（明显从负值区间抬升转正），"
        "而非仅微弱翻正。如果 MA60_ANGLE 走强力度不足，应判为「见底预警」而非空转多。"
        "\n\n── 震荡 ──"
        "\n「短期震荡」— 均线粘合（MA20 ≈ MA60），MA60_ANGLE 在零轴附近波动，无明显方向。"
        "\n\n判断优先级：「多转空/空转多节点」> 「回调买点/反弹卖点」> 其他状态。"
        "\n\n然后用一句话总结判断依据。如果是转折节点或回调/反弹买点，指出关键K线位置。"
        "\n\n分析完毕后，请在末尾给出买卖评级："
        "在 [-100, 100] 区间内打分，负数代表看空，正数代表看多，0 为中性。"
        "用一行单独输出，格式为「买卖评级：xx」，并附一句话理由。"
        "\n\n关键操作提示（在评级理由之后单独一行输出）："
        "多转空节点 → 「操作提示：逃顶减仓」"
        "空转多节点 → 「操作提示：抄底加仓」"
        "上升趋势·回调买点 → 「操作提示：回调加仓」"
        "下降趋势·反弹卖点 → 「操作提示：反弹减仓」"
        "上升趋势·加速上行 → 「操作提示：持有」"
        "下降趋势·加速下行 → 「操作提示：观望」"
        "上升趋势·见顶预警 → 「操作提示：密切关注转空信号」"
        "下降趋势·见底预警 → 「操作提示：密切关注转多信号」"
        "短期震荡 → 不输出操作提示"
    )
